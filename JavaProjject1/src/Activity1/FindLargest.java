public class FindLargest {

    public static void main(String[] args) {

        // Numbers
        int num1 = 10;
        int num2 = 20;

        if (num1 > num2) {
            System.out.println(num1 + " is largest");
        }
        else {
            System.out.println(num2 + " is largest");
        }
    }
}
