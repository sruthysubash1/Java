package sef.module4.activity;

public class AddWholeNum {

    public static void main(String[] args) {

        int total = 0;

        // For loop to add all whole numbers from 50 to 100
        for (int i = 50; i <= 100; i++) {
            total = total+i;
        }
        // result
        System.out.println("Sum of whole numbers from 50 to 100 is: " + total);
    }
}


